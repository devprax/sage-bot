#!/usr/bin/env python3
"""Bundle the modular OpenAPI source (contracts/openapi/) into contracts/openapi.yaml.

The bundle is the single self-contained contract that code and tests load; it uses only
internal `#/components/...` references. Edit the source tree, never the bundle. `--check` exits 1 when the bundle is stale; bundle errors exit 2.

Source conventions:
- `openapi.yaml` (root): info, servers, security, tags, and `paths` binding each route to
  `paths/<resource>.yaml#/<local-key>`.
- `paths/*.yaml`: mapping of local key -> Path Item (shared path parameters at item level).
- `components/schemas/*.yaml`: mapping of schema name -> Schema. Names are globally unique.
- `components/{parameters,headers,responses,security-schemes}.yaml`: name -> component.
- References are relative (`../components/schemas/health.yaml#/Liveness`, `#/Liveness`)
  and point at a top-level name; nested JSON pointers are rejected to keep the graph flat.
- Root `components` may only re-export a component under its own name
  (`Name: {$ref: components/security-schemes.yaml#/Name}`); declare components in
  `components/`. Every security requirement must name a published security scheme.
- `$ref` is resolved only where a Reference Object can stand. Values of name-keyed maps
  (`properties`, `paths`, `responses`, ...) are resolved one by one, so a property named `$ref` is
  a property; literal data (`enum`, `const`, `default`, `example`, Example `value`, schema `examples`
  lists, `x-*`) is copied verbatim, while an OpenAPI `examples` map resolves its Example Objects.
- `callbacks`, `webhooks` and `discriminator.mapping` are rejected: their operations or string
  refs would escape the security check and ref rewriting.
"""

import sys
from collections.abc import Iterator
from pathlib import Path
from typing import Any, override

import yaml

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "contracts/openapi"
BUNDLE = ROOT / "contracts/openapi.yaml"
HEADER = (
    "# GENERATED by scripts/bundle_openapi.py from contracts/openapi/ -- do not edit.\n"
    "# Edit the source tree, then run `make contract`.\n"
)
KINDS = {
    "parameters.yaml": "parameters",
    "headers.yaml": "headers",
    "responses.yaml": "responses",
    "security-schemes.yaml": "securitySchemes",
}
COMPONENT_ORDER = ("securitySchemes", "parameters", "headers", "responses", "schemas")
METHODS = ("get", "put", "post", "delete", "options", "head", "patch", "trace")
# Keywords whose value maps arbitrary names to objects: JSON Schema maps, then OpenAPI maps.
NAME_MAPS = frozenset(
    {"properties", "patternProperties", "$defs", "dependentSchemas"}
    | {"paths", "responses", "headers", "content", "encoding", "variables"}
)
# Keywords whose value is instance data, vendor data or a name map of non-objects (property
# names -> required names, scope -> description, scheme -> scopes); never a Reference Object.
LITERALS = frozenset(
    {"enum", "const", "default", "example", "value", "dependentRequired", "scopes", "security"}
)
UNSUPPORTED = frozenset({"callbacks", "webhooks", "links", "mapping"})


def classify(key: str, value: Any) -> str:
    """How a keyword's value is walked: 'unsupported', 'literal', 'map' or 'node'."""
    if key in UNSUPPORTED:
        return "unsupported"
    if key == "examples":  # schema: list of instances; OpenAPI: map of Example Objects
        return "map" if isinstance(value, dict) else "literal"
    if key in LITERALS or key.startswith("x-"):
        return "literal"
    return "map" if key in NAME_MAPS else "node"


def iter_refs(node: Any, *, name_map: bool = False) -> Iterator[str]:
    """Yield every `$ref` that stands in a Reference Object position; skips literal data."""
    if isinstance(node, list):
        for value in node:
            yield from iter_refs(value)
        return
    if not isinstance(node, dict):
        return
    if name_map:
        for value in node.values():
            yield from iter_refs(value)
        return
    ref = node.get("$ref")
    if isinstance(ref, str):
        yield ref
    for key, value in node.items():
        if key == "components" and isinstance(value, dict):  # kind -> name -> component
            for named in value.values():
                yield from iter_refs(named, name_map=True)
            continue
        kind = classify(key, value) if key != "$ref" else "literal"
        if kind in ("map", "node"):
            yield from iter_refs(value, name_map=kind == "map")


class BundleError(Exception):
    pass


class Bundler:
    def __init__(self, source: Path = SOURCE) -> None:
        self.source = source.resolve()
        self._files: dict[Path, Any] = {}
        self.components: dict[str, dict[str, Any]] = {k: {} for k in COMPONENT_ORDER}
        self._origin: dict[tuple[str, str], Path] = {}
        self._done: set[tuple[str, str]] = set()
        self._bound: set[tuple[Path, str]] = set()

    def _rel(self, file: Path) -> str:
        return str(file.relative_to(self.source))

    def _kind(self, file: Path) -> str | None:
        rel = file.relative_to(self.source)
        if rel.parts[:2] == ("components", "schemas"):
            return "schemas"
        if rel.parts[0] == "components":
            return KINDS.get(rel.name)
        return None

    def load(self, file: Path) -> Any:
        file = file.resolve()
        if not file.is_relative_to(self.source):
            raise BundleError(f"reference escapes the source tree: {file}")
        if file not in self._files:
            if not file.is_file():
                raise BundleError(f"missing source file: {self._rel(file)}")
            try:
                data = yaml.safe_load(file.read_text())
            except yaml.YAMLError as error:
                raise BundleError(f"{self._rel(file)}: invalid YAML: {error}") from error
            if not isinstance(data, dict):
                raise BundleError(f"{self._rel(file)}: top level must be a mapping")
            self._files[file] = data
        return self._files[file]

    def _target(self, ref: str, base: Path) -> tuple[Path, str]:
        file_part, sep, pointer = ref.partition("#")
        if not sep or not pointer.startswith("/") or pointer.count("/") != 1:
            raise BundleError(f"{self._rel(base)}: unsupported $ref {ref!r}")
        file = (base.parent / file_part).resolve() if file_part else base
        name = pointer[1:]
        node = self.load(file)
        if not isinstance(node, dict) or name not in node:
            raise BundleError(f"{self._rel(base)}: unresolved $ref {ref!r}")
        return file, name

    def register(self, file: Path, name: str) -> str:
        kind = self._kind(file)
        if kind is None:
            raise BundleError(f"{self._rel(file)} is not a component file")
        key = (kind, name)
        if self._origin.setdefault(key, file) != file:
            first = self._rel(self._origin[key])
            raise BundleError(f"duplicate {kind} name {name!r} in {first} and {self._rel(file)}")
        if key not in self._done:
            self._done.add(key)  # mark before resolving: tolerates recursive schemas
            self.components[kind][name] = self.resolve(self.load(file)[name], file)
        return f"#/components/{kind}/{name}"

    def resolve(self, node: Any, base: Path, *, name_map: bool = False) -> Any:
        if isinstance(node, list):
            return [self.resolve(v, base) for v in node]
        if not isinstance(node, dict):
            return node
        if name_map:
            return {k: self.resolve(v, base) for k, v in node.items()}
        if "$ref" in node:
            if not isinstance(node["$ref"], str):
                raise BundleError(f"{self._rel(base)}: $ref must be a string, got {node['$ref']!r}")
            file, name = self._target(node["$ref"], base)
            if self._kind(file) is None:  # path items are inlined at their route
                if len(node) != 1:
                    raise BundleError(f"{self._rel(base)}: sibling keys beside a path $ref")
                self._bound.add((file, name))
                return self.resolve(self.load(file)[name], file)
            out = {"$ref": self.register(file, name)}
            out.update(self._members({k: v for k, v in node.items() if k != "$ref"}, base))
            return out
        return self._members(node, base)

    def _members(self, node: dict[str, Any], base: Path) -> dict[str, Any]:
        out: dict[str, Any] = {}
        for key, value in node.items():
            kind = classify(key, value)
            if kind == "unsupported":
                raise BundleError(f"{self._rel(base)}: unsupported keyword {key!r}")
            out[key] = (
                value if kind == "literal" else self.resolve(value, base, name_map=kind == "map")
            )
        return out

    def _root_components(self, components: Any, root_file: Path) -> None:
        """Root components may only re-export source components under their own names."""
        if not isinstance(components, dict):
            raise BundleError("openapi.yaml: root components must be a mapping")
        for kind, entries in components.items():
            if kind not in self.components or not isinstance(entries, dict):
                raise BundleError(f"openapi.yaml: unsupported root components kind {kind!r}")
            for name, entry in entries.items():
                ref = entry.get("$ref") if isinstance(entry, dict) else None
                if not isinstance(ref, str) or len(entry) != 1:
                    raise BundleError(
                        f"openapi.yaml: root components.{kind}.{name} must be a $ref; "
                        "declare it under components/"
                    )
                file, target = self._target(ref, root_file)
                if self._kind(file) != kind or target != name:
                    raise BundleError(
                        f"openapi.yaml: root components.{kind}.{name} must reference a "
                        f"{kind} component named {name!r}, not {ref!r}"
                    )
                self.register(file, name)

    def _check_security(self, doc: dict[str, Any]) -> None:
        schemes = self.components["securitySchemes"]
        # Absent means "inherit" (root: none); present must be a list, possibly empty.
        where_reqs = [("openapi.yaml: security", doc.get("security", []))]
        for path, item in (doc.get("paths") or {}).items():
            for method in METHODS:
                op = item.get(method) if isinstance(item, dict) else None
                if isinstance(op, dict):
                    where_reqs.append((f"{method.upper()} {path}", op.get("security", [])))
        for where, requirements in where_reqs:
            if not isinstance(requirements, list) or not all(
                isinstance(r, dict) for r in requirements
            ):
                raise BundleError(f"{where}: security must be a list of mappings")
            for requirement in requirements:
                for scheme, scopes in requirement.items():
                    if scheme not in schemes:
                        raise BundleError(f"{where}: unknown security scheme {scheme!r}")
                    if not isinstance(scopes, list) or not all(isinstance(x, str) for x in scopes):
                        raise BundleError(f"{where}: {scheme} scopes must be a list of strings")

    def bundle(self) -> dict[str, Any]:
        root_file = self.source / "openapi.yaml"
        root = self.load(root_file)
        doc = self._members({k: v for k, v in root.items() if k != "components"}, root_file)
        self._root_components(root.get("components", {}), root_file)
        # Publish every source component, referenced or not, so the bundle never silently drops
        # a definition.
        for file in sorted((self.source / "components").rglob("*.yaml")):
            for name in self.load(file):
                self.register(file.resolve(), name)
        # A path item that no route binds would silently vanish from the contract.
        for file in sorted((self.source / "paths").glob("*.yaml")):
            for key in self.load(file):
                if (file.resolve(), key) not in self._bound:
                    raise BundleError(f"{self._rel(file)}: {key!r} is never bound to a route")
        self._check_security(doc)
        doc["components"] = {
            kind: dict(sorted(self.components[kind].items()))
            for kind in COMPONENT_ORDER
            if self.components[kind]
        }
        return doc


class _Dumper(yaml.SafeDumper):
    @override
    def ignore_aliases(self, data: Any) -> bool:
        return True


def _represent_list(dumper: yaml.SafeDumper, data: list[Any]) -> yaml.Node:
    # Short scalar lists (required, enum) read best inline.
    flow = all(isinstance(v, (str, int, float, bool)) or v is None for v in data)
    return dumper.represent_sequence("tag:yaml.org,2002:seq", data, flow_style=flow)


def _represent_str(dumper: yaml.SafeDumper, data: str) -> yaml.Node:
    style = "|" if "\n" in data else None  # multi-line prose as a literal block
    return dumper.represent_scalar("tag:yaml.org,2002:str", data, style=style)


_Dumper.add_representer(list, _represent_list)
_Dumper.add_representer(str, _represent_str)


def dump(data: Any) -> str:
    return yaml.dump(data, Dumper=_Dumper, sort_keys=False, width=100, allow_unicode=True)


def render(source: Path = SOURCE) -> str:
    return HEADER + dump(Bundler(source).bundle())


def main(argv: list[str]) -> int:
    try:
        text = render()
    except BundleError as error:
        print(f"bundle error: {error}", file=sys.stderr)
        return 2
    if "--check" in argv:
        if not BUNDLE.is_file() or BUNDLE.read_text() != text:
            print("contracts/openapi.yaml is stale; run `make contract`.", file=sys.stderr)
            return 1
        print("contracts/openapi.yaml is up to date.")
        return 0
    BUNDLE.write_text(text)
    print(f"wrote {BUNDLE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
